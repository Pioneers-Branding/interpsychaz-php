											<h4>About TMS Therapy</h4>
											<p>Transcranial Magnetic Stimulation (TMS) is an FDA-approved treatment for
												Major Depressive Disorder (MDD) since 2008, with expanded approval in
												2013 for pain relief associated with certain migraine headaches. Unlike
												Electroconvulsive Therapy (ECT), TMS is noninvasive, does not induce
												seizures, and allows patients to remain awake during the procedure. The
												treatment is well-tolerated, with mild side effects such as headaches,
												muscle twitches, and localized discomfort at the stimulation site.</p>
											<p>TMS is typically administered four to five times per week for four to six
												weeks.</p>
											<p>Research-backed protocols have been developed for TMS applications in
												treating Obsessive-Compulsive Disorder (OCD), anxiety disorders, and
												other off-label conditions, including:</p>
											<ul>
												<li>Anxiety comorbid with MDD</li>
												<li>Post-Traumatic Stress Disorder (PTSD)</li>
												<li>Chronic pain/fibromyalgia</li>
												<li>Panic disorder</li>
												<li>Cocaine addiction</li>
												<li>Tinnitus</li>
												<li>Smoking cessation</li>
											</ul>
											<p>TMS is a valuable treatment option for individuals struggling with MDD as
												defined by the DSM-V. While it may be considered a first-line treatment,
												it is most commonly recommended for patients who have not achieved
												remission after trying one or more antidepressant medications.</p>
											<h4>Theta Burst Stimulation</h4>
											<p>The Horizon 3® TMS system provides enhanced treatment versatility,
												offering multiple therapy options, including:</p>
											<ul>
												<li>Repetitive TMS (rTMS) – Standard 37.5-minute session</li>
												<li>Accelerated TMS – 19-minute session</li>
												<li>Intermittent Theta Burst Stimulation (iTBS) – A rapid 3-minute
													session with FDA clearance</li>
											</ul>
											<p>This range of treatment durations allows clinicians to tailor therapy
												based on individual patient needs.</p>
											<h4>StimGuide® 3-D Positioning System</h4>
											<p>The Horizon® Performance with StimGuide® Navigated TMS Package enhances
												treatment precision by ensuring accurate, consistent coil positioning
												across four key parameters:</p>
											<ol>
												<li><strong>Contact</strong> – Proper coil placement</li>
												<li><strong>XY Location</strong> – Precise targeting</li>
												<li><strong>Tilt</strong> – Optimal angle adjustment</li>
												<li><strong>Rotation</strong> – Consistent positioning for every session
												</li>
											</ol>
											<p>Additionally, the E-z MT® motor threshold determination process
												simplifies calibration, improving treatment accuracy and efficiency.</p>
											<h4>Electroconvulsive Therapy (ECT)</h4>
											<p>ECT is a well-established psychiatric treatment involving brief
												electrical stimulation of the brain while the patient is under
												anesthesia. A psychiatrist, along with an anesthesia team and nursing
												staff, administers the procedure in a controlled medical setting.</p>
											<p>Since its introduction in the 1940s, ECT has evolved into a highly
												effective and safe intervention for severe major depression, showing
												substantial improvement in approximately 80% of patients. It is also
												used to treat:</p>
											<ul>
												<li>Bipolar disorder</li>
												<li>Schizophrenia</li>
												<li>Catatonia</li>
											</ul>
											<p>ECT is particularly beneficial for psychiatric emergencies, including:
											</p>
											<ul>
												<li>Medically compromised catatonia</li>
												<li>Active suicidal ideations requiring rapid symptom relief</li>
											</ul>
											<p>ECT is most effective when combined with psychiatric medications and
												psychotherapy. In some cases, maintenance ECT may be recommended to
												prevent relapse after achieving symptom remission.</p>
											<h4>Spravato Esketamine Therapy</h4>
											<p>SPRAVATO® is the first FDA-approved nasal spray antidepressant, used
												alongside oral antidepressants to treat:</p>
											<ul>
												<li><strong>Treatment-resistant depression (TRD)</strong> – For adults
													who have not responded to at least two different antidepressants at
													adequate doses and durations.</li>
												<li><strong>Major Depressive Disorder (MDD)</strong> with suicidal
													thoughts or actions – Offering a rapid reduction in symptoms for
													those experiencing acute distress.</li>
											</ul>
											<p>Unlike traditional antidepressants, which can take weeks to produce
												noticeable effects, Spravato® works within 24 hours by targeting brain
												cells directly, offering fast relief for severe depressive symptoms.</p>
