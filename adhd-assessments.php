                                                <h4 style="color: #ef7136;">Inattentive Presentation</h4>
                                                <ul style="padding-left: 15px; margin-top: 10px;">
                                                    <li>Difficulty sustaining focus on tasks or play activities</li>
                                                    <li>Frequent careless mistakes in schoolwork or on the job</li>
                                                    <li>Struggling to follow through on instructions or finish chores/duties</li>
                                                    <li>Often losing things necessary for tasks (keys, wallet, assignments)</li>
                                                    <li>Easily distracted by unrelated thoughts or external stimuli</li>
                                                </ul>
                                            </div>
                                            <div style="flex: 1; min-width: 300px; background: #fff; padding: 25px; border-radius: 8px; box-shadow: 0 4px 10px rgba(0,0,0,0.05);">
                                                <h4 style="color: #ef7136;">Hyperactive-Impulsive Presentation</h4>
                                                <ul style="padding-left: 15px; margin-top: 10px;">
                                                    <li>Fidgeting, tapping hands/feet, or squirming in seat</li>
                                                    <li>Feeling restless (in adults, this often feels like an internal restlessness)</li>
                                                    <li>Talking excessively or blurting out answers prematurely</li>
                                                    <li>Difficulty waiting for one's turn in conversations or lines</li>
                                                    <li>Interrupting or intruding on others' activities</li>
