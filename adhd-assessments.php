										<p style="text-align: center; max-width: 800px; margin: 0 auto 30px;">ADHD symptoms typically fall into two main categories: Inattentive and Hyperactive-Impulsive. Many patients have a "combined" presentation. Because symptoms often look different depending on age and environment, a professional evaluation is essential.</p>
                                        
                                        <div style="display: flex; gap: 20px; flex-wrap: wrap;">
