											<h4>How long does the ADHD assessment take?</h4>
											<p>The QbCheck computer test itself takes about 15 to 20 minutes to complete. However, the test is only one part of our comprehensive evaluation. Your initial psychiatric consultation will typically last 60 to 90 minutes to ensure we gather a complete medical, behavioral, and family history.</p>

											<h4>Are assessments available via Telehealth?</h4>
											<p>Yes. We offer flexible options to meet your family's needs. While some patients prefer to come into our Phoenix clinic for their assessment, the QbCheck can be administered securely online from your own home, provided you have a compatible computer and webcam. Your clinical evaluation can also be conducted via our secure telehealth platform.</p>

											<h4>What happens after I receive a diagnosis?</h4>
											<p>If you or your child are diagnosed with ADHD, our team immediately begins developing a customized treatment plan. This often involves <a href="/medication-management/" style="color: #ef7136; text-decoration: underline;">medication management</a> (such as stimulants or non-stimulants), behavioral strategies, and lifestyle modifications. Because we handle both the testing and the medical treatment, you do not have to find a separate prescriber after your diagnosis.</p>

											<h4>Does insurance cover ADHD testing?</h4>
											<p>Many commercial insurance plans do cover psychiatric evaluations and ADHD testing when medically necessary. Our office team will verify your specific benefits prior to your appointment so you understand any out-of-pocket costs. We also offer affordable cash-pay options for patients without insurance or who prefer not to use it.</p>
