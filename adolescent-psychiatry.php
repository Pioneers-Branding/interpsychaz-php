										<div class="contentfaqs">
											<h4>When should I seek psychiatric help for my teenager?</h4>
											<p>It is normal for teenagers to experience mood swings or stress. However, if your teen is experiencing changes in mood, behavior, sleep patterns, academic performance, or social relationships that last for more than two weeks and interfere with their daily functioning, it is time to consult a psychiatric professional. Immediate help should be sought if there are any signs of self-harm or suicidal ideation.</p>

											<h4>Does psychiatric treatment always involve medication?</h4>
											<p>No, not always. While medication can be a crucial and life-saving part of a treatment plan for conditions like severe depression or ADHD, we always start with a comprehensive psychiatric evaluation. Based on the diagnosis, we may recommend a combination of lifestyle changes, school accommodations, therapy referrals, and/or medication. If medication is prescribed, it is done collaboratively and monitored very closely.</p>

											<h4>How involved can parents be in the treatment process?</h4>
											<p>For patients under 18, family involvement is not just encouraged—it is essential for long-term success. We work closely with parents and guardians to ensure they understand the treatment plan and know how to support their teen at home. For young adults over 18, we strongly encourage family involvement, though privacy laws require the patient's explicit consent to share medical details.</p>

											<h4>Do you treat ADHD in young adults?</h4>
											<p>Yes. We offer comprehensive evaluations and ongoing management for <a href="/add-adhd-testing-therapy/" style="color: #ef7136; text-decoration: underline;">Attention-Deficit/Hyperactivity Disorder (ADHD)</a>. Left untreated, ADHD in older teens and young adults can severely impact college performance and career beginnings. We provide targeted medication strategies to improve focus, organization, and emotional regulation.</p>
