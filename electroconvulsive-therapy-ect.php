										<p style="font-size: 1.1rem; line-height: 1.6;">ECT treatment involves administering a brief, controlled electrical current to the brain, which intentionally triggers a generalized seizure. This controlled seizure is the mechanism that generates the therapeutic effects of ECT. By deeply stimulating brain neurons, ECT causes a massive release of neurotransmitters (like serotonin, dopamine, and norepinephrine) that support mental health.</p>
										<p style="font-size: 1.1rem; line-height: 1.6;">Modern psychiatric research also suggests that ECT plays a critical role in increasing neuroplasticity—aiding in the formation of new neural connections and physically healing areas of the brain that have been damaged by chronic depression.</p>
