										<h3 style="color: #ef7136;">What is Electroconvulsive Therapy?</h3>
										<p>Electroconvulsive therapy (ECT) is a medical treatment primarily used for severe psychiatric disorders when other treatments—such as medications and psychotherapy—have failed to provide relief. The treatment works by delivering a brief, highly controlled electrical current to the brain while the patient is under general anesthesia, inducing a mild, therapeutic seizure.</p>
										<p>This controlled seizure stimulates rapid changes in brain chemistry and neurotransmitter activity, which can rapidly reverse symptoms of severe mental illness.</p>
