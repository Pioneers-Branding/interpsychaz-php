										<h2 style="color: #4b4d97;">Frequently Asked Questions: Depression Treatment</h2>
										<div class="contentfaqs">
											<h4>How do I know if I have depression or am just stressed?</h4>
											<p>While severe stress and grief can cause temporary sadness and mimic depressive symptoms, clinical depression typically lasts for weeks or months and significantly impairs your ability to function at work, at school, or in relationships. If your low mood is constant, accompanied by physical symptoms (like extreme fatigue or appetite changes), and doesn't lift when your stressors resolve, you should seek a psychiatric evaluation.</p>

											<h4>What is Treatment-Resistant Depression (TRD)?</h4>
											<p>Treatment-resistant depression is a clinical term used when an individual's depression does not adequately respond to at least two different antidepressant medications taken at an adequate dose and duration. If you have TRD, our clinic specializes in advanced interventional treatments like <a href="/tms-therapy/" style="color: #ef7136; text-decoration: underline;">TMS</a> and <a href="/spravato-esketamine-nasal-spray/" style="color: #ef7136; text-decoration: underline;">Spravato</a> that are specifically designed for this condition.</p>

											<h4>Do I have to take medication if I come to your clinic?</h4>
											<p>No, medication is a tool, not a requirement. During your initial consultation, we will thoroughly review your history, symptoms, and personal preferences. Many patients combine therapy with lifestyle changes. If you prefer to avoid systemic medications entirely, you may be an excellent candidate for TMS therapy.</p>

											<h4>Are depression treatments covered by insurance?</h4>
											<p>Yes. The vast majority of major commercial insurance plans, Medicare, and many AHCCCS plans cover standard psychiatric evaluations, medication management, and advanced treatments like TMS and Spravato (subject to prior authorization criteria). Our team will verify your benefits prior to your appointment so you have clarity on your coverage.</p>

                                            <h4>How do I know if I need medication or just therapy?</h4>
											<p>While talk therapy (like CBT) is excellent for processing emotions and developing coping skills, severe depression often involves a structural or chemical barrier in the brain that prevents therapy from fully working. If you feel "stuck," or if your depression symptoms are overwhelmingly physical (severe fatigue, insomnia, loss of appetite), a psychiatric evaluation for medication is highly recommended.</p>

                                            <h4>Can depression cause physical pain?</h4>
											<p>Yes. The neurotransmitters that influence pain and mood—serotonin and norepinephrine—are deeply intertwined. It is very common for clinical depression to cause unexplained physical symptoms, including chronic joint pain, limb pain, back pain, and gastrointestinal issues.</p>

                                            <h4>What if standard antidepressants make me feel "numb"?</h4>
											<p>Emotional blunting (feeling flat or numb) is a known side effect of certain SSRI medications. You do not have to live with this side effect. Our providers specialize in fine-tuning medication regimens or transitioning patients to alternative treatments (like <a href="/tms-therapy/" style="color: #ef7136; text-decoration: underline;">TMS Therapy</a>) that do not cause systemic side effects like emotional numbing or weight gain.</p>
