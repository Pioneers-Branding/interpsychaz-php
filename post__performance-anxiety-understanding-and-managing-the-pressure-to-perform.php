<p>One effective treatment for performance anxiety is cognitive-behavioral therapy (CBT). CBT is a type of talk therapy that focuses on changing negative thought patterns and behaviors that contribute to anxiety. Sports psychiatrists can work with athletes to develop personalized CBT plans that help them manage their anxiety and perform at their best.</p>
