										<div class="contentfaqs">
											<h4>Do I have to be a military veteran to have PTSD?</h4>
											<p>No. While PTSD is commonly associated with combat veterans, anyone can develop PTSD after experiencing or witnessing a traumatic event. This includes car accidents, natural disasters, sexual or physical assault, domestic violence, or sudden medical emergencies.</p>

											<h4>Can medication cure my PTSD?</h4>
											<p>Medication does not "cure" PTSD or erase traumatic memories. However, medication can significantly reduce the intensity of symptoms like anxiety, hyperarousal, and nightmares. By calming your nervous system, medication makes it much easier for you to do the deep healing work required in trauma-focused therapies like EMDR or CBT.</p>

											<h4>What is Complex PTSD (C-PTSD)?</h4>
											<p>Classic PTSD often stems from a single traumatic event. Complex PTSD (C-PTSD) results from chronic, repeated trauma over months or years, such as prolonged childhood abuse or long-term domestic violence. C-PTSD often includes additional symptoms like severe difficulty regulating emotions and deep feelings of worthlessness.</p>

                                            <h4>Can PTSD cause physical health problems?</h4>
											<p>Yes. Because PTSD keeps the body in a constant state of "fight or flight," it chronically elevates cortisol and adrenaline. Over time, this severe physiological stress can lead to cardiovascular issues, chronic pain, gastrointestinal problems, and autoimmune disorders.</p>

                                            <h4>What is the difference between PTSD and Acute Stress Disorder?</h4>
											<p>Acute Stress Disorder (ASD) involves the exact same symptoms as PTSD (flashbacks, avoidance, severe anxiety), but it occurs immediately following the trauma and lasts anywhere from three days to one month. If the symptoms persist beyond one month, the diagnosis changes to PTSD.</p>

                                            <h4>What therapies are best for PTSD?</h4>
											<p>The most heavily researched and proven psychological treatments for PTSD are Eye Movement Desensitization and Reprocessing (EMDR), Trauma-Focused Cognitive Behavioral Therapy (TF-CBT), and Prolonged Exposure (PE). We often manage your medications while you engage in these specific therapies with a trauma specialist.</p>

                                            <h4>What exactly is a "trauma trigger"?</h4>
											<p>A trigger is any sensory input—a smell, a specific sound (like a car backfiring or a raised voice), a location, or even a specific anniversary—that causes the brain to instantly recall the traumatic event. When triggered, the body reacts as if the trauma is happening right now, leading to severe anxiety or panic.</p>

                                            <h4>Can EMDR therapy be done without medication?</h4>
											<p>Yes, many patients successfully complete EMDR (Eye Movement Desensitization and Reprocessing) without medication. However, if your baseline anxiety is so high that you cannot tolerate discussing or processing the trauma, psychiatric medication is often used as a temporary bridge to make EMDR possible.</p>

                                            <h4>Is PTSD considered a disability?</h4>
											<p>Yes. Because severe PTSD can drastically impair a person's ability to work, concentrate, and interact with others, it is recognized as a disability by the ADA (Americans with Disabilities Act) and the VA (Veterans Affairs). Proper psychiatric documentation is crucial if you are seeking accommodations.</p>

                                            <h4>Is it normal to not remember parts of the traumatic event?</h4>
											<p>Yes. Dissociative amnesia is a very common biological defense mechanism. During a severe trauma, the brain's memory center (the hippocampus) can be overwhelmed by stress hormones, preventing it from properly encoding the memory. You may have blank spots in your memory of the event, which is entirely normal.</p>
