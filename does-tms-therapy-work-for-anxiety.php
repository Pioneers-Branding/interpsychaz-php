<h2 class="wp-block-heading"><strong>What to Expect During a TMS Treatment Protocol for Anxiety</strong></h2>

<p class="wp-block-paragraph">Knowing what happens during treatment can alleviate any anticipatory worry. Here is a clear overview of the clinical journey at Interventional Psychiatry of Arizona:</p>

<h3 class="wp-block-heading" style="text-align: left;">1. Initial Comprehensive Psychiatric Evaluation &amp; Brain Mapping</h3>
<p class="wp-block-paragraph">Before your first treatment, our psychiatric physician conducts a detailed assessment of your medical history, anxiety symptoms, previous medications, and treatment goals. During the initial "mapping" session, we identify your precise <strong>Motor Threshold (MT)</strong>—the minimal magnetic field required to twitch your thumb—which establishes your exact therapeutic dosing, and pinpoint the exact coordinates for coil placement over your prefrontal cortex.</p>

<h3 class="wp-block-heading" style="text-align: left;">2. Daily Treatment Sessions</h3>
<p class="wp-block-paragraph">During each session, you recline comfortably in a specialized treatment armchair. You remain fully awake and alert throughout the entire procedure. The treatment coil delivers rhythmic magnetic pulses that sound and feel like gentle tapping on the scalp. Sessions generally last between <strong>19 and 37 minutes</strong> (or 3 to 5 minutes with accelerated theta-burst protocols). Many patients listen to music, watch television, or chat with our compassionate TMS technician.</p>

<h3 class="wp-block-heading" style="text-align: left;">3. Treatment Course Duration</h3>
<p class="wp-block-paragraph">A standard clinical course consists of <strong>36 total sessions</strong> administered over 6 to 9 weeks (typically 5 sessions per week for 6 weeks, followed by a gradual 3-week taper). For a full breakdown of schedules and treatment frequency, review our guide on <a href="/how-many-sessions-of-tms-are-needed/"><strong>How Many Sessions of TMS Are Needed?</strong></a>.</p>

<h3 class="wp-block-heading" style="text-align: left;">4. Side Effects: What Are the Sensations?</h3>
<p class="wp-block-paragraph">TMS is remarkably well-tolerated. The most common side effect is mild scalp tenderness or a light tension headache during the first 1 to 2 weeks of treatment, which resolves quickly with over-the-counter pain relievers like acetaminophen or ibuprofen. There is no systemic nausea, no gastrointestinal distress, no sexual dysfunction, and no memory impairment.</p>

<h2 class="wp-block-heading"><strong>Who Is an Ideal Candidate for TMS Therapy for Anxiety?</strong></h2>

<p class="wp-block-paragraph">TMS therapy is particularly beneficial for adults who:</p>
<ul class="wp-block-list">
<li>Have been diagnosed with <strong>Generalized Anxiety Disorder (GAD)</strong>, panic disorder, or social anxiety that has not responded adequately to standard medications or psychotherapy.</li>
<li>Experience <strong>anxious depression</strong> (co-occurring major depression and severe anxiety), which represents one of the strongest clinical indications for TMS.</li>
<li>Experience intolerable side effects from prescription medications, such as severe fatigue, weight gain, brain fog, or emotional numbness.</li>
<li>Wish to taper off sedatives or benzodiazepines under medical supervision and desire a safe, non-drug neuro-restorative solution.</li>
<li>Are seeking long-term remission rather than temporary symptom management.</li>
</ul>

<p class="wp-block-paragraph">If a patient exhibits treatment-resistant depression with acute anxiety symptoms, our clinic also evaluates eligibility for breakthrough rapid-acting therapies such as <a href="/spravato-esketamine-nasal-spray/">Spravato (Esketamine) Nasal Spray</a> and comprehensive <a href="/treatments/medication-management/">personalized medication management</a>.</p>

