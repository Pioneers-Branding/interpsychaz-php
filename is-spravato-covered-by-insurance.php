<p class="wp-block-paragraph">When traditional antidepressants fail to provide relief, innovative treatments like <a href="/services/spravato-esketamine-nasal-spray/">Spravato (esketamine) nasal spray</a> offer new hope for those struggling with treatment-resistant depression (TRD) and major depressive disorder with suicidal thoughts or actions. However, navigating the healthcare system can be daunting, leading many patients at <strong>Interventional Psychiatry of Arizona</strong> to ask: <em>"Is Spravato covered by insurance?"</em></p>

<h2 class="wp-block-heading"><strong>The Short Answer: Yes, But With Requirements</strong></h2>
<p class="wp-block-paragraph">The good news is that the vast majority of commercial health insurance plans, as well as Medicare and many Medicaid programs, <strong>do cover Spravato</strong>. Because it is an FDA-approved medication with proven efficacy for severe depression, insurance companies recognize it as a medically necessary treatment for qualifying individuals.</p>
<p class="wp-block-paragraph">However, coverage is not automatic. Insurance companies require a process called "prior authorization" before they agree to pay for the medication and the associated clinic visits.</p>

<h2 class="wp-block-heading"><strong>What Does Insurance Require for Approval?</strong></h2>
<p class="wp-block-paragraph">To get Spravato covered by your insurance, you must meet specific clinical criteria to prove that the treatment is medically necessary. While every insurance plan is slightly different, the common requirements include:</p>
<ul class="wp-block-list">
<li><strong>Diagnosis:</strong> You must have a formal diagnosis of Major Depressive Disorder (MDD).</li>
<li><strong>Treatment Resistance:</strong> You must demonstrate that you have tried and failed to respond adequately to at least <strong>two different oral antidepressants</strong> from different classes, at an adequate dose and duration (usually at least 6 weeks each) during your current depressive episode.</li>
<li><strong>Concurrent Medication:</strong> Spravato is approved to be taken <em>in conjunction</em> with an oral antidepressant. Your insurance will likely require you to be taking an oral antidepressant while receiving Spravato treatments.</li>
<li><strong>Clinical Assessment:</strong> A baseline assessment of your depression severity (such as the PHQ-9 or MADRS scale) provided by your psychiatrist.</li>
</ul>

