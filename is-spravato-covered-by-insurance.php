<h2 class="wp-block-heading"><strong>Understanding the Two Parts of Spravato Billing</strong></h2>
<p class="wp-block-paragraph">When dealing with insurance for Spravato, it is important to understand that there are two separate components to the cost:</p>
<ol class="wp-block-list">
<li><strong>The Medication (Pharmacy Benefit or Medical Benefit):</strong> This is the cost of the Spravato nasal spray itself. Depending on your insurance plan, this may be billed through your pharmacy benefits (like a normal prescription) or your medical benefits (like an injection given in a doctor's office).</li>
<li><strong>The Observation Visit (Medical Benefit):</strong> Spravato must be administered under the direct supervision of a healthcare provider, followed by a mandatory two-hour observation period to monitor for side effects like dissociation or increased blood pressure. This two-hour clinic visit is billed separately under your medical benefits.</li>
</ol>

<h2 class="wp-block-heading"><strong>Out-of-Pocket Costs and Financial Assistance</strong></h2>
<p class="wp-block-paragraph">Even with insurance coverage, you may still be responsible for out-of-pocket costs, such as deductibles, copayments, or coinsurance. These costs vary wildly depending on whether you have an HMO, PPO, or a high-deductible health plan.</p>
<p class="wp-block-paragraph">Fortunately, <strong>Janssen Pharmaceuticals</strong> (the maker of Spravato) offers a robust patient assistance program called <strong>Spravato withMe</strong>. For eligible patients with commercial insurance, the Spravato Savings Program can reduce out-of-pocket costs for the medication to as little as <strong>$10 per treatment</strong>. (Note: This program generally covers the cost of the medication, not the clinic observation visit).</p>

<h2 class="wp-block-heading"><strong>Medicare and Medicaid Coverage</strong></h2>
<p class="wp-block-paragraph">If you are covered by Medicare or Medicaid, you can still access Spravato:</p>
<ul class="wp-block-list">
<li><strong>Medicare:</strong> Traditional Medicare Part B generally covers Spravato and the observation visits when administered in an outpatient psychiatric setting, provided you meet the medical necessity criteria. Medicare Advantage plans also cover it, though copays and networks vary.</li>
<li><strong>Medicaid:</strong> Most state Medicaid programs, including Arizona's AHCCCS, cover Spravato for treatment-resistant depression. Prior authorization is almost always required.</li>
</ul>

