<h3 class="faq-question" style="color: #ef7136; font-size: 19px; font-weight: 600; text-transform: none; margin-top: 24px; margin-bottom: 8px; text-align: left;">1. Does electroconvulsive therapy hurt during the procedure?</h3>
<p class="wp-block-paragraph">No. Electroconvulsive therapy does not hurt during the procedure. Patients are placed under brief general anesthesia and receive an intravenous muscle relaxant before any electrical stimulation is administered. You fall asleep within seconds, remain completely unconscious, and experience no pain, awareness, or physical discomfort during the treatment.</p>

<h3 class="faq-question" style="color: #ef7136; font-size: 19px; font-weight: 600; text-transform: none; margin-top: 24px; margin-bottom: 8px; text-align: left;">2. Will I feel an electric shock during ECT?</h3>
<p class="wp-block-paragraph">No. Because you are deeply asleep under general anesthesia, you will not feel an electric shock, burning, stinging, or buzzing sensation. The brain itself does not have sensory pain receptors, and the anesthesia ensures that the peripheral sensory nervous system is completely offline throughout the electrical pulse delivery.</p>

<h3 class="faq-question" style="color: #ef7136; font-size: 19px; font-weight: 600; text-transform: none; margin-top: 24px; margin-bottom: 8px; text-align: left;">3. Why do people believe that ECT is painful?</h3>
<p class="wp-block-paragraph">The widespread misconception that ECT is painful comes almost entirely from dramatized depictions in Hollywood films, television shows, and literature from the mid-20th century. Decades ago, prior to the routine introduction of general anesthesia and muscle relaxants in the 1950s, early unmodified shock therapy involved physical contractions. Modern medical ECT bears no resemblance to those antiquated portrayals.</p>

<h3 class="faq-question" style="color: #ef7136; font-size: 19px; font-weight: 600; text-transform: none; margin-top: 24px; margin-bottom: 8px; text-align: left;">4. What does it feel like immediately after waking up from ECT?</h3>
<p class="wp-block-paragraph">When waking up in the recovery suite 15 to 30 minutes post-procedure, most patients feel sleepy, mildly groggy, and slightly confused about the time or location for a few minutes. Some experience a mild headache, slight jaw soreness, or temporary muscle fatigue similar to the feeling after an athletic workout. These sensations fade steadily as the medications metabolize.</p>

<h3 class="faq-question" style="color: #ef7136; font-size: 19px; font-weight: 600; text-transform: none; margin-top: 24px; margin-bottom: 8px; text-align: left;">5. How severe is the headache after ECT, and how is it treated?</h3>
<p class="wp-block-paragraph">Post-ECT headaches are typically mild to moderate and feel like a dull tension headache across the forehead. They occur in about 30% to 45% of patients. Clinical teams routinely prevent or treat these headaches using intravenous or oral pain relievers, such as acetaminophen, ibuprofen, or ketorolac (Toradol), allowing patients to rest comfortably.</p>

<h3 class="faq-question" style="color: #ef7136; font-size: 19px; font-weight: 600; text-transform: none; margin-top: 24px; margin-bottom: 8px; text-align: left;">6. Does ECT cause permanent physical pain or brain damage?</h3>
<p class="wp-block-paragraph">No. Extensive scientific studies over decades confirm that modern ECT does not cause structural brain damage, permanent physical pain, or long-term bodily injury. Instead, ECT stimulates neuroplasticity, elevates Brain-Derived Neurotrophic Factor (BDNF), and resets dysfunctional neurotransmitter signaling in severe mood disorders.</p>

<h3 class="faq-question" style="color: #ef7136; font-size: 19px; font-weight: 600; text-transform: none; margin-top: 24px; margin-bottom: 8px; text-align: left;">7. How does the discomfort of ECT compare to TMS therapy?</h3>
<p class="wp-block-paragraph">TMS therapy requires no anesthesia and involves no seizures; patients sit comfortably in a treatment chair and feel a rapid tapping sensation on the scalp, with zero post-session grogginess. In contrast, ECT requires general anesthesia and induces a brief, controlled seizure, making it more intensive but accompanied by mild post-anesthesia fatigue. Both procedures are safe and carefully managed for patient comfort.</p>

