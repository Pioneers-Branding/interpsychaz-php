<h2 class="wp-block-heading"><strong>What Does ECT Feel Like When You Wake Up? Post-Treatment Sensations</strong></h2>

<p class="wp-block-paragraph">While there is zero pain during treatment, understanding post-procedure recovery helps set clear expectations. Waking up from ECT feels very similar to recovering from minor outpatient surgery:</p>

<ul class="wp-block-list">
<li><strong>Mild Tension Headache:</strong> Roughly 30% to 45% of patients note a mild, dull headache across the forehead or temples due to transient vascular dilation. It responds quickly to acetaminophen or ibuprofen.</li>
<li><strong>Muscle Soreness:</strong> Some experience minor jaw, neck, or calf stiffness, similar to a light workout. This temporary side effect of succinylcholine dissipates within hours.</li>
<li><strong>Post-Anesthesia Grogginess:</strong> Feeling sleepy or mildly hazy for 20 to 45 minutes is typical as anesthetics clear. Full clarity returns as you rest.</li>
<li><strong>Mild Nausea:</strong> Anesthesia can occasionally cause minor stomach queasiness, which our team prevents using intravenous anti-nausea medications like ondansetron.</li>
<li><strong>Short-Term Memory Fog:</strong> Modern unilateral electrode protocols have minimized cognitive side effects. Any mild forgetfulness typically surrounds treatment hours and resolves over several weeks.</li>
</ul>

