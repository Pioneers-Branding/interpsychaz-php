<h3 class="faq-question" style="color: #ef7136; font-size: 19px; font-weight: 600; text-transform: none; margin-top: 24px; margin-bottom: 8px; text-align: left;">1. Can TMS therapy make depression permanently worse?</h3>
<p class="wp-block-paragraph">No. Rigorous clinical trials across more than 20 years confirm that Transcranial Magnetic Stimulation does not cause permanent neurological harm, structural brain damage, or long-term worsening of depression. When symptoms do not improve, it represents treatment non-response rather than biological deterioration.</p>

<h3 class="faq-question" style="color: #ef7136; font-size: 19px; font-weight: 600; text-transform: none; margin-top: 24px; margin-bottom: 8px; text-align: left;">2. What causes the "TMS Dip" and how long does it last?</h3>
<p class="wp-block-paragraph">The TMS dip occurs in roughly 15% to 20% of patients around weeks 2 to 4 (sessions 10 to 20). It is caused by active synaptic reorganization and neuroplastic adaptation as dormant neural circuits in the prefrontal cortex wake up. The dip is temporary, typically lasting between 3 and 7 days before mood steadily improves.</p>

<h3 class="faq-question" style="color: #ef7136; font-size: 19px; font-weight: 600; text-transform: none; margin-top: 24px; margin-bottom: 8px; text-align: left;">3. Can TMS cause suicidal thoughts like antidepressant medications?</h3>
<p class="wp-block-paragraph">No. Unlike many SSRIs and SNRIs that carry an FDA black box warning for increased suicidal thoughts in young adults, clinical studies demonstrate that TMS consistently and significantly decreases suicidal ideation across treatment courses.</p>

<h3 class="faq-question" style="color: #ef7136; font-size: 19px; font-weight: 600; text-transform: none; margin-top: 24px; margin-bottom: 8px; text-align: left;">4. Can TMS trigger anxiety or mania?</h3>
<p class="wp-block-paragraph">In rare cases, patients with underlying unmanaged bipolar disorder may experience a manic or hypomanic switch from high-frequency excitatory stimulation. For this reason, comprehensive diagnostic screening is conducted prior to treatment. If anxiety symptoms arise, clinicians can adjust parameters by incorporating low-frequency inhibitory stimulation on the right prefrontal cortex.</p>

<h3 class="faq-question" style="color: #ef7136; font-size: 19px; font-weight: 600; text-transform: none; margin-top: 24px; margin-bottom: 8px; text-align: left;">5. Does TMS therapy cause memory loss?</h3>
<p class="wp-block-paragraph">No. Unlike Electroconvulsive Therapy (ECT), TMS does not cause generalized seizures, requires no anesthesia, and does not cause memory impairment, confusion, or cognitive decline. Clinical research actually shows that many patients experience enhanced executive function and mental clarity as depression lifts.</p>

<h3 class="faq-question" style="color: #ef7136; font-size: 19px; font-weight: 600; text-transform: none; margin-top: 24px; margin-bottom: 8px; text-align: left;">6. What should I do if I feel worse during TMS therapy?</h3>
<p class="wp-block-paragraph">Immediately notify your treatment team. Your psychiatric provider can evaluate whether you are experiencing the normal transient TMS dip, re-verify your Motor Threshold, adjust coil placement, or modify pulse intensity. Continuing through the full 36-session series is essential for consolidating neuroplastic improvements.</p>

<h3 class="faq-question" style="color: #ef7136; font-size: 19px; font-weight: 600; text-transform: none; margin-top: 24px; margin-bottom: 8px; text-align: left;">7. What are the options if TMS does not resolve my depression?</h3>
<p class="wp-block-paragraph">If a full course of TMS does not provide relief, patients have several viable advanced options. These include transitioning to accelerated theta-burst protocols, exploring Spravato (esketamine nasal spray) for rapid NMDA glutamate receptor modulation, or adjusting personalized medication management strategies.</p>

